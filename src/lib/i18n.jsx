const STRINGS = { en, th }
const TITLES = { en: en.page_title, th: th.page_title }

const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  // Default language is THAI (owner's call, 2026-10-17): TruePin is a
  // Thai site first. A visitor's stored choice ('en') still wins.
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('tre-lang') === 'en' ? 'en' : 'th'
    } catch {
      return 'th'
    }
  })

  useEffect(() => {
    try {
      localStorage.setItem('tre-lang', lang)
    } catch {
      /* ignore */
    }
    document.title = TITLES[lang]
    document.documentElement.lang = lang === 'th' ? 'th' : 'en'
  }, [lang])

  const t = (key, vars) => {
    let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(`{${k}}`, String(v))
      }
    }
    return s
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLang() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLang must be used inside LanguageProvider')
  return ctx
}

